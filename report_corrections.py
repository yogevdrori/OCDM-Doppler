"""
Corrections for the report (Overleaf Sec. 4 = Step 4 Part D + the
bias-phase check) after the std-err audit (audit_bias_se.py). No new
simulation.

(i)   Step 4 Part D, Delta = {0}: bias +/- std err in the layout of
      results/loop_sim.md, old (spread of the R = 8 realisation means) and
      corrected (batch means of >= 10 loop time constants, 16 batches; see
      the audit), and the "high-SNR bias floor is 7-19 std errors from zero"
      statement recomputed.
(ii)  bias_phase_check.md: no raw data was saved; corrected std errs:
      - a also run in Step 4 (5e-4, -5e-4, 1e-3, 1e-4): the Step 4
        corrected se at the same SNR x sqrt(16000 / 12000) (R L = 8 x 2000
        there, 4 x 3000 here);
      - other a: model se (sigma_e/K_d)/sqrt(R L) x the median ratio
        corrected/model of the Step 4 runs at that SNR (conservative: the
        integer-a runs, with correlated detector noise, dominate it).
(iii) fig_loop_bias_vs_snr_corr.png: the normalised-bias plot of Step 4
      with the corrected error bars (the original is not overwritten).

Output: results/report_corrections.md, figures/fig_loop_bias_vs_snr_corr.png
"""

from __future__ import annotations

import math
import re
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np

import audit_bias_se as ab

ROOT = Path(__file__).parent
RES = ROOT / "results"
WP_DB = 4.0


def step4_rows():
    rows = []
    for f in sorted((RES / "loop_raw").glob("*.npz")):
        z = np.load(f)
        cfg = f.stem.split("_")[0]
        a, D = float(z["a"]), int(z["discard"])
        for s, snr in enumerate(z["snrs"]):
            x = z["a_hat"][:, s, D + 1:] - a
            r = ab.audit(x, old_method="real", tau_design=100.0)
            r.update(cfg=cfg, a=a, snr=float(snr))
            rows.append(r)
    return rows


def main():
    rows = step4_rows()
    lag0 = [r for r in rows if r["cfg"] == "lag0"]
    L = ["# Corrections for the report after the std-err audit", "",
         "Generated by `report_corrections.py` (no new simulation). Method: "
         "see the script docstring and `results/bias_se_audit.md`. The "
         "loop output is correlated over ≈ 1/B_L ≈ 200 blocks; the corrected "
         "std err uses batch means of ≥ 10 loop time constants (Step 4: 16 "
         "batches of 1000 blocks) or, where no raw data exists, the model "
         "(σ_e/K_d)/√(R L) calibrated on Step 4.", ""]

    # (i) statement
    floor = [r for r in lag0 if abs(r["a"]) >= 5e-4 and
             (np.isinf(r["snr"]) or r["snr"] == 20.0)]
    zo = [abs(r["bias"]) / r["se_old"] for r in floor]
    zn = [abs(r["bias"]) / r["se_new"] for r in floor]
    small = [r for r in lag0 if abs(r["a"]) < 5e-4 and
             (np.isinf(r["snr"]) or r["snr"] == 20.0)]
    L += ["## (i) Step 4 Part D: high-SNR bias floor", "",
          "Statement in the report: *\"It is 7–19 standard errors from "
          "zero.\"* This range is reproduced by |a| ∈ {5e-4, 1e-3} at ∞ and "
          f"20 dB (old: {min(zo):.1f}–{max(zo):.1f}).", "",
          f"**Corrected: {min(zn):.1f}–{max(zn):.1f} standard errors from "
          "zero** (per value below). The conclusion — a real, a-dependent "
          "bias floor of 1–2e-6 at high SNR — is unchanged.", "",
          "| a | SNR (dB) | bias | old z | corrected z |", "|---|---|---|---|---|"]
    for r, a_, b_ in zip(floor, zo, zn):
        L.append(f"| {r['a']:+.0e} | {ab.snr_s(r['snr'])} | {r['bias']:+.2e} "
                 f"| {a_:.1f} | {b_:.1f} |")
    L += ["", "For |a| = 1e-4 (not in the statement): " + "; ".join(
        f"{r['a']:+.0e} at {ab.snr_s(r['snr'])} dB: "
        f"{abs(r['bias']) / r['se_old']:.1f} → "
        f"{abs(r['bias']) / r['se_new']:.1f}" for r in small) + ".", ""]

    # (i) table in the loop_sim layout
    L += ["### Δ = {0} table (loop_sim.md layout; R = 8, L = 2000)", "",
          "| a | SNR (dB) | bias | ± std err (old) | ± std err (corrected) | "
          "norm. bias | z old → corrected | change |",
          "|---|---|---|---|---|---|---|---|"]
    for r in sorted(lag0, key=lambda r: (r["a"], -r["snr"]
                                         if np.isfinite(r["snr"]) else -99)):
        snr = "∞" if np.isinf(r["snr"]) else (
            f"{r['snr']:g} (WP)" if r["snr"] == WP_DB else f"{r['snr']:g}")
        L.append(f"| {r['a']:+.0e} | {snr} | {r['bias']:+.2e} | "
                 f"{r['se_old']:.1e} | {r['se_new']:.1e} | "
                 f"{r['bias'] / r['a']:+.3f} | {r['z_old']:.1f} → "
                 f"{r['z_new']:.1f} | {ab.flag(r)} |")
    L.append("")

    # (ii) bias-phase table
    txt = (RES / "bias_phase_check.md").read_text(encoding="utf-8")
    bp = re.findall(r"\| ([+-][\d.e+-]+) \| ([+-][\d.]+) \| ([\d.]+) \| "
                    r"([+-][\d.e+-]+) ± ([\d.e+-]+) \| ([+-][\d.e+-]+) ± "
                    r"([\d.e+-]+) \|", txt)
    step4 = {(round(r["a"], 10), r["snr"]): r for r in lag0}
    infl, model_se = {}, {}
    for snr in (float("inf"), WP_DB):
        rs = [r for r in lag0 if r["snr"] == snr]
        infl[snr] = float(np.median([r["se_new"] / r["se_mod"] for r in rs]))
        # sigma_e/K_d = std(eps) * sqrt(1/B_L), median over the Step 4 runs
        model_se[snr] = float(np.median([r["se_mod"] * math.sqrt(r["R"] *
                                                                 r["L"])
                                         for r in rs])) / math.sqrt(12000)
    scale = math.sqrt(16000 / 12000)

    def corr(a, snr):
        r = step4.get((round(a, 10), snr))
        if r is not None:
            return r["se_new"] * scale, "Step 4"
        return model_se[snr] * infl[snr], "model×infl."
    L += ["## (ii) Bias-phase table (bias_phase_check.md layout)", "",
          "Corrected ± (R = 4 × L = 3000, pole 0.99). Inflation factor "
          "corrected/model from Step 4: noiseless "
          f"{infl[float('inf')]:.2f}, 4 dB {infl[WP_DB]:.2f}; model se "
          f"(σ_e/K_d)/√12000: noiseless {model_se[float('inf')]:.1e}, 4 dB "
          f"{model_se[WP_DB]:.1e}.", "",
          "| a | a*N_c (samples/block) | frac | bias noiseless | bias 4 dB |",
          "|---|---|---|---|---|"]
    detail = ["", "Old → corrected std err and significance:", "",
              "| a | SNR | bias | old ± | corrected ± (source) | z old → "
              "corrected | change |", "|---|---|---|---|---|---|---|"]
    for a, aNc, frac, b0, se0, b4, se4 in bp:
        a_ = float(a)
        c0, s0 = corr(a_, float("inf"))
        c4, s4 = corr(a_, WP_DB)
        L.append(f"| {a} | {aNc} | {frac} | {float(b0):+.2e} ± {c0:.1e} | "
                 f"{float(b4):+.2e} ± {c4:.1e} |")
        for snr, b, so, sn, src in ((float("inf"), b0, se0, c0, s0),
                                    (WP_DB, b4, se4, c4, s4)):
            b, so = float(b), float(so)
            zo_, zn_ = abs(b) / so, abs(b) / sn
            ch = ""
            for lev in (3, 2):
                if (zo_ >= lev) != (zn_ >= lev):
                    ch = f"**{'lost' if zo_ >= lev else 'gained'} {lev}σ**"
                    break
            detail.append(f"| {a} | {ab.snr_s(snr)} | {b:+.2e} | {so:.1e} | "
                          f"{sn:.1e} ({src}) | {zo_:.1f} → {zn_:.1f} | {ch} |")
    L += detail + [""]

    # (iii) figure
    import study_loop as sl
    finite = [s for s in sl.SNRS if np.isfinite(s)]
    a_set = sorted({r["a"] for r in lag0})
    cmap = plt.get_cmap("coolwarm")
    col = {a: cmap(i / (len(a_set) - 1)) for i, a in enumerate(a_set)}

    def series(a, key):
        rr = {r["snr"]: r for r in lag0 if r["a"] == a}
        return [rr[s][key] if key != "nb" else rr[s]["bias"] / a
                for s in finite if s in rr]
    with plt.rc_context({"font.size": 11}):
        fig, ax = plt.subplots(figsize=(7.5, 5))
        for a in a_set:
            ax.errorbar(finite, series(a, "nb"),
                        yerr=np.array(series(a, "se_new")) / abs(a),
                        fmt="o-", color=col[a], capsize=3, ms=4,
                        label=f"a = {a:+.0e}")
        ax.axhline(0, color="0.3", lw=0.7)
        ax.axvline(WP_DB, color="0.5", ls=":", lw=1)
        ax.set_xlabel(r"$\sigma_D^2/P_n$ (dB)")
        ax.set_ylabel(r"normalised bias  $E\{\hat a - a\}/a$")
        ax.set_title("Closed loop, Δ = {0}: normalised bias vs SNR (± 1 "
                     "std err, corrected: batches ≥ 10 τ)", fontsize=10)
        ax.grid(True, color="0.9", lw=0.5)
        ax.legend(fontsize=9, ncol=2)
        fig.tight_layout()
        fig.savefig(ROOT / "figures" / "fig_loop_bias_vs_snr_corr.png",
                    dpi=150)
        plt.close(fig)
    changed = [r for r in rows if ab.flag(r)]
    L += ["## (iii) Figure", "",
          "`figures/fig_loop_bias_vs_snr_corr.png`: as fig_loop_bias_vs_snr "
          "(Δ = {0}, finite SNRs, normalised bias ± 1 std err) with the "
          "corrected error bars; the original is unchanged. Error bars "
          "change by a factor "
          f"{min(r['se_new'] / r['se_old'] for r in lag0 if np.isfinite(r['snr'])):.2f}"
          f"–{max(r['se_new'] / r['se_old'] for r in lag0 if np.isfinite(r['snr'])):.2f}.",
          "", f"The {len(changed)} Step 4 figures whose significance changed, "
          "and whether they are visible in that plot (it shows Δ = {0} at "
          "finite SNRs only):", "",
          "| config | a | SNR | z old → corrected | change | in the plot |",
          "|---|---|---|---|---|---|"]
    for r in changed:
        vis = "yes" if (r["cfg"] == "lag0" and np.isfinite(r["snr"])) else (
            "no (Δ = {0..15})" if r["cfg"] != "lag0" else "no (∞ dB)")
        L.append(f"| {'Δ = {0}' if r['cfg'] == 'lag0' else 'Δ = {0..15}'} | "
                 f"{r['a']:+.0e} | {ab.snr_s(r['snr'])} | {r['z_old']:.1f} → "
                 f"{r['z_new']:.1f} | {ab.flag(r)} | {vis} |")
    L.append("")
    (RES / "report_corrections.md").write_text("\n".join(L),
                                               encoding="utf-8")
    print("\n".join(L))


if __name__ == "__main__":
    main()
