"""
Step 4, Parts C and D: first-order Doppler loop (ocdm_doppler/loop.py).

Part C  95 % convergence time n95 = ln(0.05)/ln(p) for p in {0.9, 0.95,
        0.99} and N_c in {24000, 12000, 6000}, in blocks and seconds at
        4 MHz; K_d measured per N_c (noiseless, open loop: mu = 0, a_hat
        fixed at a -/+ 2e-4); verified by a noiseless step response from
        a_hat_0 = 0 (8 realisations, a = 5e-4).

Part D  closed loop vs SNR (see run_part_d): pole 0.99, a_hat_0 = 0,
        a in {+/-1e-4, +/-5e-4, +/-1e-3}, steady state after the transient.

Lag set Delta = {0} unless stated (params.with_(cbsfs_deltas=(0,))).
Settings: 22-Jan preset (BPSK), N_seg = 2048, delta = 0.25/N_seg, k = 1,
seeds 1000 + realisation index.

Usage:
    python study_loop.py --part C [--quick]
    python study_loop.py --part D [--quick] [--resume] [--replot]
"""

from __future__ import annotations

import argparse
import csv
import math
import time
from multiprocessing import Pool
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np

from ocdm_doppler import preset_noisy_22jan
from ocdm_doppler import loop as lp

ROOT = Path(__file__).parent
RES, FIG = ROOT / "results", ROOT / "figures"
F_SAMP = 4e6
N_SEG = 2048
POLES = (0.9, 0.95, 0.99)
N_CS = (24000, 12000, 6000)
LAG0 = (0,)


def base(lags=LAG0):
    return preset_noisy_22jan(float("inf")).with_(cbsfs_deltas=lags)


# ---------------------------------------------------------------------------
# Part C
# ---------------------------------------------------------------------------
def _kd_job(args):
    n_c, d, seed, n_blk = args
    a = 5e-4
    r = lp.run_loop(base(), a, mu=0.0, n_blocks=n_blk, a_hat0=a + d,
                    N_c=n_c, N_seg=N_SEG, seed=seed)
    return r.e[0]


def _step_job(args):
    n_c, mu, n_blk, seed = args
    r = lp.run_loop(base(), 5e-4, mu=mu, n_blocks=n_blk, a_hat0=0.0,
                    N_c=n_c, N_seg=N_SEG, seed=seed)
    return r.a_hat[0]


def part_c(quick: bool, procs: int):
    t0 = time.time()
    n_kd = 4 if quick else 32
    n_real = 2 if quick else 8
    d = 2e-4
    kd = {}
    with Pool(procs) as pool:
        for n_c in N_CS:
            jobs = [(n_c, s * d, 1000 + r, n_kd) for s in (-1, 1)
                    for r in range(4)]
            res = pool.map(_kd_job, jobs)
            e_lo = np.concatenate(res[:4])          # a_hat = a - d: e > 0
            e_hi = np.concatenate(res[4:])
            kd[n_c] = (e_lo.mean() - e_hi.mean()) / (2 * d)
            print(f"  K_d(N_c={n_c}) = {kd[n_c]:.1f}  "
                  f"({e_lo.size} blocks per side) [{time.time() - t0:.0f}s]",
                  flush=True)

        steps = {}
        for p_ in POLES:
            for n_c in N_CS:
                nb = int(math.ceil(3 * lp.n95(p_)))
                if quick and p_ == 0.99:
                    nb = 60
                mu = (1 - p_) / kd[n_c]
                trajs = pool.map(_step_job, [(n_c, mu, nb, 1000 + r)
                                             for r in range(n_real)])
                steps[(p_, n_c)] = np.array(trajs)
                print(f"  step p={p_} N_c={n_c}: {nb} blocks x {n_real} "
                      f"[{time.time() - t0:.0f}s]", flush=True)

    a = 5e-4
    rows, L = [], []
    L += ["# First-order loop: 95 % convergence time (Part C)", "",
          "Generated by `study_loop.py --part C`. Loop a_hat[i+1] = a_hat[i] "
          "+ μ e[i], one update per block of N_c samples, g = μ K_d, pole "
          "p = 1 − g, n95 = ln(0.05)/ln(p). Δ = {0}, δ = 0.25/N_seg, "
          "N_seg = 2048, f_samp = 4 MHz.", "",
          "## Detector gain per block length (noiseless, open loop)", "",
          "| N_c | N_c / (2 N_seg) | K_d |", "|---|---|---|"]
    for n_c in N_CS:
        L.append(f"| {n_c} | {n_c / (2 * N_SEG):.2f} | {kd[n_c]:.1f} |")
    L += ["", "## n95: analytical and simulated (noiseless step response "
          f"0 → a = 5e-4, mean of {n_real} realisations)", "",
          "| pole p | N_c | block (ms) | n95 analytical (blocks) | "
          "n95 analytical (s) | n95 simulated (blocks) | final mean â/a − 1 "
          "(last n95 blocks) |",
          "|---|---|---|---|---|---|---|"]
    for p_ in POLES:
        for n_c in N_CS:
            tr = steps[(p_, n_c)]
            err = (a - tr.mean(0)) / a
            idx = np.flatnonzero(np.abs(err) <= 0.05)
            n_sim = int(idx[0]) if idx.size else float("nan")
            n_an = lp.n95(p_)
            blk = n_c / F_SAMP
            tail = tr[:, -int(math.ceil(n_an)):]
            fin = float(tail.mean() / a - 1)
            fin_se = float(tail.mean(1).std() / a / np.sqrt(tr.shape[0]))
            rows.append(dict(pole=p_, N_c=n_c, K_d=kd[n_c], block_ms=blk * 1e3,
                             n95_blocks=n_an, n95_seconds=n_an * blk,
                             n95_sim_blocks=n_sim, final_rel_err=fin,
                             final_rel_err_se=fin_se))
            L.append(f"| {p_} | {n_c} | {blk * 1e3:.1f} | {n_an:.1f} | "
                     f"{n_an * blk:.3f} | {n_sim} | {fin:+.3f} ± "
                     f"{fin_se:.3f} |")
    L += ["",
          "n95 in blocks does not depend on N_c (the loop is designed per "
          "N_c with μ = (1 − p)/K_d(N_c)); in seconds it scales with N_c. "
          "Simulated n95: first block with |a − mean â| ≤ 0.05 a. "
          f"N_c = 6000 is only {6000 / (2 * N_SEG):.2f} × 2N_seg: the "
          "autocorrelated CAF then uses (N_c − 2N_seg + 1)/N_c = "
          f"{(6000 - 2 * N_SEG + 1) / 6000:.0%} of the samples "
          f"(vs {(24000 - 2 * N_SEG + 1) / 24000:.0%} at N_c = 24000), so "
          "the detector noise per block is larger.", ""]
    out = RES / ("quick" if quick else "")
    out.mkdir(parents=True, exist_ok=True)
    with open(out / "loop_convergence.csv", "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0]))
        w.writeheader()
        w.writerows(rows)
    (out / "loop_convergence.md").write_text("\n".join(L), encoding="utf-8")
    print("\n".join(L))

    figd = out if quick else FIG
    fig, axes = plt.subplots(1, 3, figsize=(13, 3.8), sharey=True)
    for ax, p_ in zip(axes, POLES):
        for n_c, c in zip(N_CS, ("#1f77b4", "#ff7f0e", "#2ca02c")):
            tr = steps[(p_, n_c)]
            ax.plot(tr.mean(0) / a, color=c, lw=1.4, label=f"N_c = {n_c}")
        n_an = lp.n95(p_)
        ax.plot(1 - p_ ** np.arange(int(3 * n_an) + 1), "k--", lw=1,
                label=r"$1-p^n$")
        ax.axvline(n_an, color="0.4", ls=":", lw=1)
        ax.axhline(0.95, color="0.4", ls=":", lw=1)
        ax.set_title(f"pole p = {p_}: n95 = {n_an:.0f} blocks", fontsize=11)
        ax.set_xlabel("block")
        ax.grid(True, color="0.9", lw=0.5)
    axes[0].set_ylabel(r"mean $\hat a$ / a")
    axes[0].legend(fontsize=8.5, loc="lower right")
    fig.suptitle("Noiseless step response of the first-order loop, a = 5e-4, "
                 "Δ = {0}", fontsize=11)
    fig.tight_layout()
    fig.savefig(figd / "fig_loop_step.png", dpi=150)
    plt.close(fig)
    print(f"runtime {time.time() - t0:.0f}s")
    return kd


# ---------------------------------------------------------------------------
# Part D
# ---------------------------------------------------------------------------
A_SET = (-1e-3, -5e-4, -1e-4, 1e-4, 5e-4, 1e-3)
WP_DB = 4.0
SNRS = (float("inf"), 20.0, 10.0, 7.5, 5.0, WP_DB, 2.5, 0.0, -5.0)
POLE = 0.99
# main run (Delta = {0}) and the reduced full-lag-set comparison (D.7)
CONFIGS = {
    "lag0": dict(lags=(0,), lagset="0", a_set=A_SET, snrs=SNRS, R=8, L=2000),
    "lagall": dict(lags=None, lagset="0..15", a_set=(1e-4, 1e-3),
                   snrs=(20.0, WP_DB, 0.0), R=4, L=1000),
}


def part_b_table():
    """K_d and sigma_e per (lag set, SNR) from results/characteristic.csv."""
    out = {}
    with open(RES / "characteristic.csv", newline="") as f:
        for r in csv.DictReader(f):
            out[(r["lagset"], float(r["snr_db"]))] = (float(r["Kd"]),
                                                      float(r["sigma_e"]))
    return out


def design(cfg, tab):
    """mu from the noiseless K_d; transient discard = 3 n95 of the slowest
    SNR (gain K_d(SNR) / K_d0 < 1 at low SNR slows the loop)."""
    kd0 = tab[(cfg["lagset"], float("inf"))][0]
    mu = (1 - POLE) / kd0
    g_min = min(mu * tab[(cfg["lagset"], s)][0] for s in cfg["snrs"])
    discard = int(math.ceil(3 * lp.n95(1 - g_min)))
    return kd0, mu, discard


def _d_job(args):
    lags, a, mu, n_blk, snrs, seed = args
    r = lp.run_loop(base(lags), a, mu=mu, n_blocks=n_blk, snrs=snrs,
                    a_hat0=0.0, N_c=24000, N_seg=N_SEG, seed=seed)
    return r.a_hat


def run_part_d(args):
    t0 = time.time()
    tab = part_b_table()
    out = RES / ("quick" if args.quick else "")
    raw = out / "loop_raw"
    raw.mkdir(parents=True, exist_ok=True)
    figd = out if args.quick else FIG
    figd.mkdir(parents=True, exist_ok=True)
    if not (args.resume or args.replot):
        for f in raw.glob("*.npz"):
            f.unlink()

    data = {}
    n_new = 0
    with Pool(args.procs) as pool:
        for name, cfg in CONFIGS.items():
            kd0, mu, discard = design(cfg, tab)
            R, L = cfg["R"], cfg["L"]
            if args.quick:
                R, L, discard = 2, 50, 30
            for a in cfg["a_set"]:
                f = raw / f"{name}_a{a:+.0e}.npz"
                if f.exists():
                    d = np.load(f)
                    if d["a_hat"].shape[0] == R:
                        data[(name, a)] = (d["a_hat"], int(d["discard"]), mu)
                        continue
                if args.replot:
                    raise SystemExit(f"--replot: missing {f.name}")
                if args.max_new is not None and n_new >= args.max_new:
                    print(f"--max-new reached; rerun with --resume "
                          f"[{time.time() - t0:.0f}s]")
                    return
                n_new += 1
                ts = time.time()
                # per-realisation part files, so one case can be split over
                # several calls (--max-real); merged once all R exist
                part = [raw / f"{f.stem}_r{r}.npy" for r in range(R)]
                todo = [r for r in range(R) if not part[r].exists()]
                if args.max_real is not None:
                    todo = todo[:args.max_real]
                res = pool.map(_d_job, [
                    (cfg["lags"], a, mu, discard + L, cfg["snrs"], 1000 + r)
                    for r in todo])
                for r, tr in zip(todo, res):
                    np.save(part[r], tr)
                if not all(pt.exists() for pt in part):
                    print(f"  {name} a={a:+.0e}: realisations "
                          f"{sum(pt.exists() for pt in part)}/{R} saved; "
                          f"rerun with --resume [{time.time() - ts:.0f}s]")
                    return
                traj = np.array([np.load(pt) for pt in part])
                np.savez(f, a_hat=traj, discard=discard, mu=mu, a=a,
                         snrs=cfg["snrs"], R=R, L=L)
                for pt in part:
                    pt.unlink()
                data[(name, a)] = (traj, discard, mu)
                print(f"  {name} a={a:+.0e}: R={R} x {discard}+{L} blocks "
                      f"[{time.time() - ts:.0f}s, total "
                      f"{time.time() - t0:.0f}s]", flush=True)
    analyse_part_d(data, tab, out, figd, args.quick)
    print(f"runtime {time.time() - t0:.0f}s")


def _lag1(x):
    x = x - x.mean()
    return float(np.sum(x[1:] * x[:-1]) / np.sum(x * x))


def analyse_part_d(data, tab, out, figd, quick):
    rows = []
    for (name, a), (traj, discard, mu) in data.items():
        cfg = CONFIGS[name]
        for s_i, snr in enumerate(cfg["snrs"]):
            post = traj[:, s_i, discard + 1:]                 # R x L
            R, L = post.shape
            err = post - a
            bias = float(err.mean())
            bias_se = float(post.mean(1).std(ddof=1) / np.sqrt(R)) if R > 1 \
                else float("nan")
            mse = float(np.mean(err ** 2))
            var = float(np.mean((post - post.mean()) ** 2))
            rho = float(np.mean([_lag1(x) for x in post]))
            n_eff_var = R * L * (1 - rho ** 2) / (1 + rho ** 2)
            n_eff_mean = R * L * (1 - rho) / (1 + rho)
            e_loop = np.diff(traj[:, s_i, discard:], axis=1) / mu
            kd, sig_e = tab[(cfg["lagset"], snr)]
            kd0 = tab[(cfg["lagset"], float("inf"))][0]
            g, g_eff = mu * kd0, mu * kd
            pred_spec = lp.steady_state_var(sig_e / kd0, g)
            pred_eff = lp.steady_state_var(sig_e / kd, g_eff)
            rows.append(dict(
                config=name, lagset=cfg["lagset"], a=a, snr_db=snr, R=R, L=L,
                discard=discard, bias=bias, bias_se=bias_se,
                norm_bias=bias / a, nmse=mse / a ** 2, rmse=math.sqrt(mse),
                var=var, var_pred_spec=pred_spec, var_pred_gain=pred_eff,
                nmse_pred=pred_eff / a ** 2, var_ratio=var / pred_eff,
                rho=rho, n_eff_var=n_eff_var, n_eff_mean=n_eff_mean,
                sigma_e_loop=float(e_loop.std()), sigma_e_partB=sig_e,
                g=g, g_eff=g_eff))
    rows.sort(key=lambda r: (r["config"], r["a"], -r["snr_db"]))
    with open(out / "loop_sim.csv", "w", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=list(rows[0]))
        w.writeheader()
        w.writerows(rows)

    def snr_s(s):
        return "∞" if np.isinf(s) else (f"{s:g} (WP)" if s == WP_DB
                                        else f"{s:g}")

    L_ = ["# Closed-loop simulation (Part D)", "",
          "Generated by `study_loop.py --part D`. First-order loop, pole "
          f"p = {POLE} (μ = (1 − p)/K_d0, K_d0 = noiseless gain of the lag "
          "set), â_0 = 0, one update per block of N_c = 24000 samples; "
          "δ = 0.25/N_seg, N_seg = 2048, 22-Jan preset (BPSK). SNR = "
          "σ_D²/P_n; WP = 4.0 dB (BPSK SER = 10 %).", "",
          "Steady state: blocks after a transient of 3·n95 of the slowest "
          "SNR (the gain g_eff = μ K_d(SNR) is smaller at low SNR), "
          "R realisations × L blocks. The loop output is correlated (lag-1 "
          "correlation ρ ≈ 1 − g_eff); effective numbers of independent "
          "samples: N_eff(var) = RL(1 − ρ²)/(1 + ρ²), N_eff(mean) = "
          "RL(1 − ρ)/(1 + ρ). Bias std err from the spread of the R "
          "realisation means.", "",
          "Prediction: var = (σ_e/K_d)² g/(2 − g) with σ_e from Part B. "
          "'spec': K_d = K_d0, g = μK_d0 (= 0.01); 'gain': K_d = K_d(SNR), "
          "g = μK_d(SNR) (the gain actually seen at that SNR). NMSE pred. "
          "uses 'gain' and zero bias.", ""]
    for name, cfg in CONFIGS.items():
        sel = [r for r in rows if r["config"] == name]
        if not sel:
            continue
        L_ += [f"## Δ = {{{cfg['lagset']}}}  (R = {sel[0]['R']}, L = "
               f"{sel[0]['L']}, transient discarded: {sel[0]['discard']} "
               "blocks)", "",
               "| a | SNR (dB) | bias | ± std err | norm. bias | NMSE | "
               "NMSE pred. | var / pred. | RMSE | N_eff (var / mean) | "
               "σ_e in loop / Part B |",
               "|---|---|---|---|---|---|---|---|---|---|---|"]
        for r in sel:
            L_.append(
                f"| {r['a']:+.0e} | {snr_s(r['snr_db'])} | {r['bias']:+.2e} | "
                f"{r['bias_se']:.1e} | {r['norm_bias']:+.3f} | "
                f"**{r['nmse']:.2e}** | {r['nmse_pred']:.2e} | "
                f"{r['var_ratio']:.2f} | {r['rmse']:.2e} | "
                f"{r['n_eff_var']:.0f} / {r['n_eff_mean']:.0f} | "
                f"{r['sigma_e_loop']:.2e} / {r['sigma_e_partB']:.2e} |")
        L_.append("")
    (out / "loop_sim.md").write_text("\n".join(L_), encoding="utf-8")
    print("\n".join(L_))
    plot_part_d(data, rows, figd)


def plot_part_d(data, rows, figd):
    sel = [r for r in rows if r["config"] == "lag0"]
    a_set = sorted({r["a"] for r in sel})
    cmap = plt.get_cmap("coolwarm")
    col = {a: cmap(i / (len(a_set) - 1)) for i, a in enumerate(a_set)}
    finite = [s for s in SNRS if np.isfinite(s)]

    def series(a, key):
        rr = {r["snr_db"]: r for r in sel if r["a"] == a}
        return [rr[s][key] for s in finite if s in rr]

    with plt.rc_context({"font.size": 11}):
        # NMSE vs SNR
        fig, ax = plt.subplots(figsize=(7.5, 5))
        for a in a_set:
            ax.semilogy(finite, series(a, "nmse"), "o-", color=col[a],
                        label=f"a = {a:+.0e}")
            ax.semilogy(finite, series(a, "nmse_pred"), "--", color=col[a],
                        lw=1)
        ax.plot([], [], "k--", lw=1, label="linear prediction")
        ax.axvline(WP_DB, color="0.5", ls=":", lw=1)
        ax.set_xlabel(r"$\sigma_D^2/P_n$ (dB)")
        ax.set_ylabel(r"NMSE  $E\{(\hat a - a)^2\}/a^2$")
        ax.set_title("Closed loop, Δ = {0}, pole 0.99: NMSE vs SNR "
                     "(dotted: WP)", fontsize=11)
        ax.grid(True, which="both", color="0.9", lw=0.5)
        ax.legend(fontsize=9, ncol=2)
        fig.tight_layout()
        fig.savefig(figd / "fig_loop_nmse_vs_snr.png", dpi=150)
        plt.close(fig)

        # normalised bias vs SNR
        fig, ax = plt.subplots(figsize=(7.5, 5))
        for a in a_set:
            ax.errorbar(finite, series(a, "norm_bias"),
                        yerr=np.array(series(a, "bias_se")) / abs(a),
                        fmt="o-", color=col[a], capsize=3, ms=4,
                        label=f"a = {a:+.0e}")
        ax.axhline(0, color="0.3", lw=0.7)
        ax.axvline(WP_DB, color="0.5", ls=":", lw=1)
        ax.set_xlabel(r"$\sigma_D^2/P_n$ (dB)")
        ax.set_ylabel(r"normalised bias  $E\{\hat a - a\}/a$")
        ax.set_title("Closed loop, Δ = {0}: normalised bias vs SNR "
                     "(± 1 std err)", fontsize=11)
        ax.grid(True, color="0.9", lw=0.5)
        ax.legend(fontsize=9, ncol=2)
        fig.tight_layout()
        fig.savefig(figd / "fig_loop_bias_vs_snr.png", dpi=150)
        plt.close(fig)

        # vs a at the working point (closed-loop characteristic)
        fig, axes = plt.subplots(1, 2, figsize=(12, 4.6))
        sc = 1e3
        for snr, c in ((20.0, "#1f77b4"), (WP_DB, "#d62728"),
                       (0.0, "#2ca02c")):
            rr = sorted([r for r in sel if r["snr_db"] == snr],
                        key=lambda r: r["a"])
            x = np.array([r["a"] for r in rr])
            m = np.array([r["a"] + r["bias"] for r in rr])
            sd = np.sqrt([r["var"] for r in rr])
            lbl = f"{snr:g} dB" + (" (WP)" if snr == WP_DB else "")
            axes[0].errorbar(x * sc, m * sc, yerr=sd * sc, fmt="o", color=c,
                             capsize=3, label=lbl)
            axes[1].semilogy(x * sc, [r["nmse"] for r in rr], "o-", color=c,
                             label=lbl)
            axes[1].semilogy(x * sc, [r["nmse_pred"] for r in rr], "--",
                             color=c, lw=1)
        axes[0].plot([-1.1, 1.1], [-1.1, 1.1], "k--", lw=1,
                     label="unbiased")
        axes[0].set_xlabel(r"true $a$ ($\times 10^{-3}$)")
        axes[0].set_ylabel(r"mean $\hat a$ ($\times 10^{-3}$), ± 1 std")
        axes[0].set_title("closed-loop estimate vs true a", fontsize=11)
        axes[1].set_xlabel(r"true $a$ ($\times 10^{-3}$)")
        axes[1].set_ylabel("NMSE")
        axes[1].set_title("NMSE vs true a (dashed: prediction)", fontsize=11)
        for ax in axes:
            ax.grid(True, which="both", color="0.9", lw=0.5)
            ax.legend(fontsize=9)
        fig.tight_layout()
        fig.savefig(figd / "fig_loop_vs_a.png", dpi=150)
        plt.close(fig)

        # trajectories at the working point
        fig, ax = plt.subplots(figsize=(10, 4.6))
        for a in a_set:
            traj, discard, mu = data[("lag0", a)]
            s_i = CONFIGS["lag0"]["snrs"].index(WP_DB)
            for r in range(min(3, traj.shape[0])):
                ax.plot(traj[r, s_i] * sc, color=col[a], lw=0.6,
                        alpha=0.8, label=f"a = {a:+.0e}" if r == 0 else None)
            ax.axhline(a * sc, color=col[a], ls=":", lw=0.8)
        ax.axvline(lp.n95(POLE), color="0.3", ls="--", lw=1,
                   label=f"n95 = {lp.n95(POLE):.0f}")
        ax.axvline(discard, color="0.6", ls="--", lw=1,
                   label=f"end of discarded transient ({discard})")
