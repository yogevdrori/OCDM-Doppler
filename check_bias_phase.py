"""
Hypothesis test: is the closed-loop bias floor caused by a frozen sampling
phase?

For a constant a, every block of N_c = 24000 samples starts a*N_c samples
later (relative to the symbol grid) than the nominal position. If a*N_c is an
integer (a = 2.5e-4, 5e-4, 1e-3, ...), every block sees the same sub-sample
sampling phase and, with N_sym = 20, only a few symbol phases, so a
phase-dependent detector offset does not average out. For a*N_c = integer +
0.37 the phase changes from block to block and the offset should average.

Pairs: a_int with a*N_c integer (or 2.4 for 1e-4) and a_int + 0.37/N_c
(or - 0.37/N_c for 1e-3, to stay in the prior range).
Loop: Delta = {0}, pole 0.99, a_hat0 = a, transient 900 blocks (3 n95),
R = 4 realisations x L = 3000 blocks, noiseless and 4 dB in lockstep.
Bias = mean(a_hat - a); standard error from the spread of the realisation
means. Writes results/bias_phase_check.md.
"""

import math
import time
from multiprocessing import Pool
from pathlib import Path

import numpy as np

from ocdm_doppler import preset_noisy_22jan
from ocdm_doppler import loop as lp

N_C = 24000
KD0 = 175.5
MU = 0.01 / KD0
DISCARD, L, R = 900, 3000, 4
SNRS = (float("inf"), 4.0)
SHIFT = 0.37 / N_C
PAIRS = [(2.5e-4, +SHIFT), (5e-4, +SHIFT), (-5e-4, +SHIFT),
         (1e-3, -SHIFT), (1e-4, +SHIFT)]
OUT = Path(__file__).parent / "results" / "bias_phase_check.md"


def job(args):
    a, r = args
    p = preset_noisy_22jan(20.0).with_(cbsfs_deltas=(0,))
    res = lp.run_loop(p, a, mu=MU, n_blocks=DISCARD + L, snrs=SNRS,
                      a_hat0=a, N_c=N_C, seed=1000 + r)
    return a, r, (res.a_hat[:, DISCARD + 1:] - a).mean(axis=1)


def main():
    t0 = time.time()
    a_list = []
    for a, d in PAIRS:
        a_list += [a, a + d]
    jobs = [(a, r) for a in a_list for r in range(R)]
    means = {}
    with Pool(2) as pool:
        for a, r, m in pool.imap_unordered(job, jobs):
            means.setdefault(a, []).append(m)
            print(f"a={a:+.4e} r={r} bias={m} [{time.time() - t0:.0f}s]",
                  flush=True)
    lines = ["# Bias vs sampling phase (hypothesis check)", "",
             "Generated by `check_bias_phase.py` (see docstring). Delta = {0}, "
             "pole 0.99, a_hat0 = a, transient 900, R = 4 x L = 3000. "
             "Bias = mean(a_hat - a) +/- standard error of the realisation "
             "means.", "",
             "| a | a*N_c (samples/block) | frac | bias noiseless | "
             "bias 4 dB |", "|---|---|---|---|---|"]
    for a in a_list:
        m = np.array(means[a])
        b = m.mean(axis=0)
        se = m.std(axis=0, ddof=1) / math.sqrt(R)
        x = a * N_C
        lines.append(f"| {a:+.4e} | {x:+.2f} | {x - math.floor(x):.2f} | "
                     f"{b[0]:+.2e} ± {se[0]:.1e} | {b[1]:+.2e} ± {se[1]:.1e} |")
    lines += ["", f"Runtime {time.time() - t0:.0f} s."]
    OUT.write_text("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
